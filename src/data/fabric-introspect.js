// CLI: npm run fabric:introspect
//
// Discovers the Fabric lakehouse schema live from INFORMATION_SCHEMA and writes
// a REVIEWED, CHECKED-IN catalog artifact (src/data/catalogs/fabricLakehouse.js).
// Runtime never auto-discovers: a schema change is a deliberate re-introspection
// and code review, exactly like the Azure SQL catalog.
//
// Connects with YOUR signed-in identity (az login / DefaultAzureCredential), so
// what you see here is what a user with your Fabric permissions would see.
const fs = require("fs");
const path = require("path");
const sql = require("mssql");
const { DefaultAzureCredential } = require("@azure/identity");
const config = require("../config");

// Fabric's SQL analytics endpoint speaks TDS and wants the standard SQL
// audience — NOT api.fabric.microsoft.com.
const TDS_SCOPE = "https://database.windows.net/.default";

// System/telemetry schemas the model must never see.
const HIDDEN_SCHEMAS = new Set(["queryinsights", "sys", "INFORMATION_SCHEMA", "dbo_internal"]);

const TYPE_MAP = {
    int: "number", bigint: "number", smallint: "number", tinyint: "number",
    decimal: "number", numeric: "number", float: "number", real: "number", money: "number",
    bit: "boolean",
    date: "date", datetime: "date", datetime2: "date", smalldatetime: "date", datetimeoffset: "date",
};
function jsType(sqlType) {
    return TYPE_MAP[String(sqlType).toLowerCase()] || "string";
}

function sqlTypeExpr(dataType, maxLen) {
    const t = String(dataType).toLowerCase();
    if (["varchar", "nvarchar", "char", "nchar"].includes(t)) {
        const len = maxLen === -1 || maxLen == null ? "sql.MAX" : Math.min(maxLen, 4000);
        return `sql.NVarChar(${len})`;
    }
    if (t === "int") return "sql.Int";
    if (t === "bigint") return "sql.BigInt";
    if (t === "bit") return "sql.Bit";
    if (["decimal", "numeric"].includes(t)) return "sql.Decimal(18, 4)";
    if (["float", "real"].includes(t)) return "sql.Float";
    if (t.includes("date")) return "sql.DateTime2";
    return "sql.NVarChar(4000)";
}

async function main() {
    if (!config.fabricEndpoint || !config.fabricDatabase) {
        throw new Error("FABRIC_SQL_ENDPOINT and FABRIC_DATABASE must be set.");
    }
    const credential = new DefaultAzureCredential();
    const token = await credential.getToken(TDS_SCOPE);

    const pool = await new sql.ConnectionPool({
        server: config.fabricEndpoint,
        database: config.fabricDatabase,
        authentication: { type: "azure-active-directory-access-token", options: { token: token.token } },
        // MANDATORY: omitting these fails the Entra handshake and looks exactly
        // like a bad password.
        options: { encrypt: true, trustServerCertificate: false },
        connectionTimeout: 60000,
        requestTimeout: 60000,
    }).connect();

    const result = await pool.request().query(`
        SELECT c.TABLE_SCHEMA, c.TABLE_NAME, c.COLUMN_NAME, c.DATA_TYPE,
               c.CHARACTER_MAXIMUM_LENGTH, c.ORDINAL_POSITION
        FROM INFORMATION_SCHEMA.COLUMNS c
        JOIN INFORMATION_SCHEMA.TABLES t
          ON t.TABLE_SCHEMA = c.TABLE_SCHEMA AND t.TABLE_NAME = c.TABLE_NAME
        WHERE t.TABLE_TYPE = 'BASE TABLE'
        ORDER BY c.TABLE_SCHEMA, c.TABLE_NAME, c.ORDINAL_POSITION
    `);
    await pool.close();

    const tables = {};
    for (const r of result.recordset) {
        if (HIDDEN_SCHEMAS.has(r.TABLE_SCHEMA)) continue;
        const key = r.TABLE_NAME;
        if (!tables[key]) {
            tables[key] = { schema: r.TABLE_SCHEMA, name: r.TABLE_NAME, columns: [] };
        }
        tables[key].columns.push({
            name: r.COLUMN_NAME,
            dataType: r.DATA_TYPE,
            maxLength: r.CHARACTER_MAXIMUM_LENGTH,
        });
    }

    const names = Object.keys(tables);
    console.log(`Discovered ${names.length} table(s) in ${config.fabricDatabase}:`);
    for (const n of names) {
        console.log(`  ${tables[n].schema}.${n} (${tables[n].columns.length} columns)`);
        console.log(`      ${tables[n].columns.map((c) => `${c.name}:${c.dataType}`).join(", ")}`);
    }

    // ---- emit the reviewable catalog artifact -----------------------------
    const alphabet = "abcdefghijklmnopqrstuvwxyz";
    const lines = [];
    lines.push("// GENERATED by `npm run fabric:introspect`, then REVIEWED and checked in.");
    lines.push("// Runtime does not auto-discover: re-run introspection deliberately when the");
    lines.push("// lakehouse schema changes, then review this file.");
    lines.push("//");
    lines.push("// Edit freely: descriptions, labels, and which columns are exposed are");
    lines.push("// curation decisions. Anything not listed here is NOT addressable.");
    lines.push('const sql = require("mssql");');
    lines.push("");
    lines.push("const TABLES = {");
    names.forEach((n, i) => {
        const t = tables[n];
        const alias = alphabet[i] + (i > 25 ? String(i) : "");
        lines.push(`    ${n}: {`);
        lines.push(`        sqlName: "${t.schema}.${t.name}",`);
        lines.push(`        alias: "${alias}",`);
        lines.push(`        description: "TODO: describe ${t.name}.",`);
        lines.push("        columns: {");
        for (const c of t.columns) {
            const type = jsType(c.dataType);
            const groupable = type !== "string" || (c.maxLength && c.maxLength <= 200 && c.maxLength !== -1);
            lines.push(`            ${c.name}: {`);
            lines.push(`                sqlName: "${alias}.${c.name}",`);
            lines.push(`                label: "${c.name}",`);
            lines.push(`                type: "${type}",`);
            lines.push(`                description: "${c.name} (${c.dataType}).",`);
            lines.push(`                selectable: true,`);
            lines.push(`                filterable: true,`);
            lines.push(`                groupable: ${groupable ? "true" : "false"},`);
            lines.push(`                aggregatable: ${type === "number" ? "true" : "false"},`);
            lines.push(`                sqlType: () => ${sqlTypeExpr(c.dataType, c.maxLength)},`);
            lines.push("            },");
        }
        lines.push("        },");
        lines.push("    },");
    });
    lines.push("};");
    lines.push("");
    lines.push("// No joins declared until a relationship is reviewed and added deliberately.");
    lines.push("const JOINS = {};");
    lines.push("");
    lines.push("module.exports = {");
    lines.push("    name: \"fabric\",");
    lines.push("    TABLES,");
    lines.push("    JOINS,");
    lines.push("    // SCOPE POLICY (required — a source with no declared policy fails at startup).");
    lines.push("    // Fabric enforces the SIGNED-IN USER's own workspace/table permissions on the");
    lines.push("    // TDS connection itself, so there is no row-level predicate to add here: the");
    lines.push("    // engine will not return rows the user may not see. This is 'enforced by the");
    lines.push("    // source', which is materially different from 'no scope at all'.");
    lines.push("    scope: { policy: \"enforced_by_source\", table: null, column: null },");
    lines.push("};");

    const outDir = path.join(__dirname, "catalogs");
    fs.mkdirSync(outDir, { recursive: true });
    const outPath = path.join(outDir, "fabricLakehouse.generated.js");
    fs.writeFileSync(outPath, lines.join("\n") + "\n");
    console.log(`\nCatalog draft written to ${outPath}`);
    console.log("Review it, curate descriptions/exposed columns, then save as fabricLakehouse.js");
}

main().catch((err) => {
    console.error("Fabric introspection failed:", err.message);
    process.exit(1);
});
